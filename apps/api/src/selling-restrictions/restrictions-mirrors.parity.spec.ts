import {
  RESTRICTION_ADDRESS_PRECEDENCE_VALUES as SHARED,
  API_ERROR_CODES as SHARED_CODES,
  DRIVER_RESTRICTION_BLOCK_MESSAGE as SHARED_DRIVER_MESSAGE,
  RESTRICTION_OVERRIDE_IMPORTED_REASON as SHARED_IMPORTED_REASON,
  RESTRICTION_OVERRIDE_LABEL as SHARED_LABEL,
  RESTRICTION_OVERRIDE_REASON_MAX as SHARED_MAX,
  RESTRICTION_OVERRIDE_REASON_MIN as SHARED_MIN,
} from "@routeflow/types";
import { RESTRICTION_ADDRESS_PRECEDENCE_VALUES } from "./selling-restrictions.service";
import {
  DRIVER_RESTRICTION_BLOCK_MESSAGE,
  RESTRICTION_OVERRIDE_CODES,
  RESTRICTION_OVERRIDE_IMPORTED_REASON,
  RESTRICTION_OVERRIDE_LABEL,
  RESTRICTION_OVERRIDE_REASON_MAX,
  RESTRICTION_OVERRIDE_REASON_MIN,
} from "./override-constants";

describe("API-local mirrors of shared restriction constants", () => {
  it("RESTRICTION_ADDRESS_PRECEDENCE_VALUES is set-equal to the shared array", () => {
    expect(SHARED.length).toBeGreaterThan(0);
    expect(new Set(RESTRICTION_ADDRESS_PRECEDENCE_VALUES)).toEqual(new Set(SHARED));
    expect(RESTRICTION_ADDRESS_PRECEDENCE_VALUES).toHaveLength(SHARED.length);
  });

  it("row 510: the override reason bounds, driver message, note label and import marker equal the shared ones", () => {
    expect(RESTRICTION_OVERRIDE_REASON_MIN).toBe(SHARED_MIN);
    expect(RESTRICTION_OVERRIDE_REASON_MAX).toBe(SHARED_MAX);
    expect([RESTRICTION_OVERRIDE_REASON_MIN, RESTRICTION_OVERRIDE_REASON_MAX]).toEqual([3, 200]);
    expect(DRIVER_RESTRICTION_BLOCK_MESSAGE).toBe(SHARED_DRIVER_MESSAGE);
    expect(RESTRICTION_OVERRIDE_LABEL).toBe(SHARED_LABEL);
    expect(RESTRICTION_OVERRIDE_IMPORTED_REASON).toBe(SHARED_IMPORTED_REASON);
  });

  it("row 510: the protocol's two codes are the shared RESTRICTION_WARNING and RESTRICTION_OVERRIDE_REASON_INVALID", () => {
    expect(RESTRICTION_OVERRIDE_CODES).toEqual({
      warning: SHARED_CODES.RESTRICTION_WARNING,
      reasonInvalid: SHARED_CODES.RESTRICTION_OVERRIDE_REASON_INVALID,
    });
    expect(RESTRICTION_OVERRIDE_CODES.warning).toBe("RESTRICTION_WARNING");
  });
});
