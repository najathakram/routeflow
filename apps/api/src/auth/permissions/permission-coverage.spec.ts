import * as fs from "fs";
import * as path from "path";
import { OperatorPermissionGroup } from "@prisma/client";
import { accessOf, allHandlers, handlersIn } from "./permission-discovery";
import { PERMISSION_MAP } from "./permission-map.pinned";

/**
 * spec-operator-permissions §4.4: every controller handler an OPERATOR can reach names a permission group (or is
 * `@PermissionBase` on purpose); every admin-only handler carries neither; and the discovered map equals the checked-in
 * `permission-map.pinned.ts` in BOTH directions, so any access change is a two-place diff a reviewer sees. Discovery is
 * static (TypeScript AST), so a comment or a string never counts and no Nest bootstrap is needed.
 * Regenerate the pinned file with `UPDATE_PERMISSION_MAP=1 npx jest src/auth/permissions/permission-coverage.spec.ts`.
 */
/**
 * Groups that ship before the handler they gate, each with its ruling. An entry must name a real group that gates
 * nothing yet; the spec below goes red once a handler uses it, so the entry is removed in that PR.
 */
const GATE_LANDS_LATER: Readonly<Record<string, string>> = {
  BAD_DEBT:
    "SA-1050: PR-0 ships the group, denied by default, with no reader; PR-3's write-off and reinstate handlers gate on it",
};

/** The groups a pinned map's values open ("A|B" = any-of); BASE, ADMIN and UNGUARDED open none. */
function usedGroups(map: Readonly<Record<string, string>>): Set<string> {
  return new Set(
    Object.values(map)
      .flatMap((v) =>
        /^[A-Z_|]+$/.test(v) && !["BASE", "ADMIN", "UNGUARDED"].includes(v) ? v.split("|") : [],
      )
      .sort(),
  );
}

const SRC = path.resolve(__dirname, "../..");
const handlers = allHandlers(SRC);
const discovered: Record<string, string> = {};
for (const h of handlers) {
  const a = accessOf(h);
  if (a) discovered[h.key] = a;
}

describe("operator permission coverage (spec §4.4)", () => {
  it("discovers a real controller surface (a spec that finds nothing must fail, L-202)", () => {
    expect(handlers.length).toBeGreaterThan(500);
    expect(Object.keys(discovered).length).toBeGreaterThan(400);
  });

  it("every handler an operator can reach names a group or is PermissionBase", () => {
    const undecorated = Object.entries(discovered)
      .filter(([, v]) => v === "UNDECORATED")
      .map(([k]) => k);
    expect(undecorated).toEqual([]);
  });

  it("an admin-only handler carries neither a group nor PermissionBase (a contradiction)", () => {
    const bad = handlers
      .filter((h) => h.roles && !h.roles.includes("OPERATOR") && h.roles.includes("TENANT_ADMIN"))
      .filter((h) => h.permission && !h.permissionFromClass)
      .map((h) => h.key);
    expect(bad).toEqual([]);
  });

  it("a PermissionBase handler states its reason (a non-empty string literal)", () => {
    const base = handlers.filter((h) => h.permission?.kind === "BASE");
    expect(base.length).toBeGreaterThan(0);
    const bare = base.filter(
      (h) => h.permission?.kind === "BASE" && h.permission.reason.trim().length < 8,
    );
    expect(bare.map((h) => h.key)).toEqual([]);
  });

  it("the discovered map equals the pinned map, both directions", () => {
    if (process.env.UPDATE_PERMISSION_MAP === "1") {
      const body = Object.keys(discovered)
        .sort()
        .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(discovered[k])},`)
        .join("\n");
      fs.writeFileSync(
        path.join(__dirname, "permission-map.pinned.ts"),
        `/**\n * The pinned operator-access map (spec-operator-permissions §4.3/§4.4): "Controller.method" -> the groups that open it\n * ("A|B" = any-of), BASE (any operator, on purpose), ADMIN (@Roles TENANT_ADMIN only) or UNGUARDED (no @Roles).\n * Generated by permission-coverage.spec.ts; a diff here is an access change and must be reviewed as one.\n */\nexport const PERMISSION_MAP: Readonly<Record<string, string>> = {\n${body}\n};\n`,
      );
      return;
    }
    const missingFromPin = Object.keys(discovered).filter((k) => !(k in PERMISSION_MAP));
    const extraInPin = Object.keys(PERMISSION_MAP).filter((k) => !(k in discovered));
    const changed = Object.keys(discovered)
      .filter((k) => k in PERMISSION_MAP && PERMISSION_MAP[k] !== discovered[k])
      .map((k) => `${k}: pinned ${PERMISSION_MAP[k]}, now ${discovered[k]}`);
    expect({ missingFromPin, extraInPin, changed }).toEqual({
      missingFromPin: [],
      extraInPin: [],
      changed: [],
    });
  });

  it("every permission group gates at least one handler (no dead switch)", () => {
    const used = usedGroups(PERMISSION_MAP);
    for (const g of Object.values(OperatorPermissionGroup).filter((x) => !(x in GATE_LANDS_LATER)))
      expect([g, used.has(g)]).toEqual([g, true]);
  });

  it("a group whose gate lands later is a real group that gates nothing yet (drop the entry when it does)", () => {
    const used = usedGroups(PERMISSION_MAP);
    const groups: readonly string[] = Object.values(OperatorPermissionGroup);
    for (const [g, why] of Object.entries(GATE_LANDS_LATER)) {
      expect([g, groups.includes(g)]).toEqual([g, true]);
      expect([g, used.has(g)]).toEqual([g, false]);
      expect(why.length).toBeGreaterThan(20);
    }
  });

  it("the group parser counts an underscore group, alone and in an any-of", () => {
    expect([
      ...usedGroups({ "A.a": "BAD_DEBT", "B.b": "FINANCE|BAD_DEBT", "C.c": "BASE" }),
    ]).toEqual(["BAD_DEBT", "FINANCE"]);
  });

  describe("the discovery (positive controls on inline source)", () => {
    const src = `
      @RequirePermission("ORDERS")
      @Controller("x")
      class XController {
        @Get("a") @Roles(UserRole.OPERATOR) a() {}
        @Get("b") @Roles(UserRole.OPERATOR) @PermissionBase("a lookup other areas need") b() {}
        @Post("c") @Roles(UserRole.TENANT_ADMIN) c() {}
        @Get("d") d() {}
        @Get("e") @Roles(UserRole.OPERATOR) @RequirePermission("FINANCE", "ORDERS") e() {}
        notAHandler() {}
      }
      // @RequirePermission("CATALOG") class Fake {}
    `;
    const map = Object.fromEntries(
      handlersIn("x.controller.ts", src).map((h) => [h.key, accessOf(h)]),
    );
    it("reads class default, method override, base, admin-only and unguarded", () => {
      expect(map).toEqual({
        "XController.a": "ORDERS",
        "XController.b": "BASE",
        "XController.c": "ADMIN",
        "XController.d": "UNGUARDED",
        "XController.e": "FINANCE|ORDERS",
      });
    });
    it("flags an operator handler with no decoration", () => {
      const bare = handlersIn(
        "y.controller.ts",
        `@Controller("y") class Y { @Get() @Roles(UserRole.OPERATOR) z() {} }`,
      );
      expect(accessOf(bare[0])).toBe("UNDECORATED");
    });
  });
});
