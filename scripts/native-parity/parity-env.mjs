#!/usr/bin/env node
/**
 * #2338: the ONLY writer of the mobile dev-parity sign-in env (security tier 1, the lead's guards).
 *
 *   node scripts/native-parity/parity-env.mjs write --state loaded|empty
 *     writes the GITIGNORED apps/mobile/.env.parity (root .gitignore `.env.*`) with
 *     EXPO_PUBLIC_PARITY_LOGIN from the local `test` seed's fixtures (fixtures.cjs) and a LOCAL
 *     EXPO_PUBLIC_API_URL. No credential is ever a literal in app code.
 *   node scripts/native-parity/parity-env.mjs start --state loaded|empty
 *     writes it, then runs `expo start --ios` (Expo Go on the booted simulator) with exactly that env;
 *     lib/dev-parity-login.ts signs the buyer in at boot. Restart it to switch state.
 *
 * The API URL is always http://localhost:3000. The app-side guard accepts ONLY the simulator's own
 * loopback over http(s) (localhost, 127.0.0.1, ::1, 10.0.2.2) and refuses LAN or deployed hosts.
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const { REPO_ROOT } = require("./paths.cjs");
const { PARITY_BUYER, PARITY_BUYER_EMPTY, PARITY_TENANT_SLUG } = require("./fixtures.cjs");

const MOBILE = join(REPO_ROOT, "apps", "mobile");
const ENV_FILE = join(MOBILE, ".env.parity");
const API_URL = "http://localhost:3000";

export function parityEnv(state) {
  const fx = { loaded: PARITY_BUYER, empty: PARITY_BUYER_EMPTY }[state];
  if (!fx) throw new Error(`--state must be loaded or empty, got "${state}"`);
  return {
    EXPO_PUBLIC_PARITY_LOGIN: JSON.stringify({
      email: fx.email,
      password: fx.password,
      seller: PARITY_TENANT_SLUG,
    }),
    EXPO_PUBLIC_API_URL: API_URL,
  };
}

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

function main() {
  const cmd = process.argv[2];
  const state = arg("--state", "loaded");
  const env = parityEnv(state);
  const body =
    "# GENERATED by scripts/native-parity/parity-env.mjs (#2338). Gitignored. Local test fixture only.\n" +
    Object.entries(env)
      .map(([k, v]) => `${k}=${JSON.stringify(v)}`)
      .join("\n") +
    "\n";
  writeFileSync(ENV_FILE, body, { mode: 0o600 });
  console.log(`wrote ${ENV_FILE} (${state} buyer, API ${API_URL})`);
  if (cmd === "start") {
    const r = spawnSync("npx", ["expo", "start", "--ios", "--clear"], {
      cwd: MOBILE,
      stdio: "inherit",
      env: { ...process.env, ...env },
    });
    process.exit(r.status ?? 1);
  } else if (cmd !== "write") {
    throw new Error("usage: parity-env.mjs write|start --state loaded|empty");
  }
}

main();
